// Generates drivers/mixxx/EP-DJ3000.midi.xml from the contract constants.
//
//   node drivers/test/mixxx/gen-xml.mjs           write the file
//   node drivers/test/mixxx/gen-xml.mjs --check   exit 1 if the checked-in file differs
//
// Mixxx matches an input on the exact status byte, and does not fold Note Off
// into Note On, so every note is bound twice (0x9n and 0x8n) per deck channel.
// The unit may send either form for a release (PROTOCOL.md 2.1).

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const P = require(join(here, "../../common/epdj3000-protocol.js"));

export const XML_PATH = join(here, "../../mixxx/EP-DJ3000.midi.xml");
export const PREFIX = "EPDJ3000Mixxx";
export const SCRIPT_FILES = [
  { filename: "epdj3000-protocol.js" },
  { filename: "EP-DJ3000-scripts.js", functionprefix: PREFIX },
];

// handler = property of the script object; cc = names in P.cc; note = name in P.note.
const CONTROLS = [
  { handler: "jog", cc: ["jog"], desc: "platter motion (relative CC, 1024 ticks/rev): scratch when touched, pitch bend otherwise" },
  { handler: "touch", note: "touch", desc: "platter touch: scratch mode on/off" },
  { handler: "cue", note: "cue", desc: "CUE button" },
  { handler: "rev", note: "rev", desc: "REV button" },
  { handler: "play", note: "play", desc: "play/pause toggle (platter tap)" },
  { handler: "tap", note: "tap", desc: "tap tempo" },
  { handler: "crossfader", cc: ["crossfaderMsb", "crossfaderLsb"], desc: "slide pot as crossfader (14-bit)" },
  { handler: "channelVolume", cc: ["channelVolumeMsb", "channelVolumeLsb"], desc: "slide pot as channel volume (14-bit)" },
  { handler: "pitch", cc: ["pitchMsb", "pitchLsb"], desc: "slide pot as tempo fader (14-bit)" },
  { handler: "knob", cc: ["knobMsb", "knobLsb"], desc: "orange knob as Quick Effect / filter (14-bit)" },
  { handler: "bpm", cc: ["bpmMsb", "bpmLsb"], desc: "set tempo, value = BPM x 10 (14-bit)" },
  { handler: "bpmNudge", cc: ["bpmNudge"], desc: "tempo change, 0.1 BPM per step (relative CC)" },
  { handler: "transport", cc: ["transport"], desc: "absolute transport state: 0 stop, 1 play, 2 pause" },
];

const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(2, "0");

function control(deckName, deck, spec, status, midino, label) {
  return `
            <control>
                <description>${deckName} - ${spec.desc} - ${label}</description>
                <group>[Channel${deck}]</group>
                <key>${PREFIX}.${spec.handler}</key>
                <status>${hex(status)}</status>
                <midino>${hex(midino)}</midino>
                <options>
                    <Script-Binding/>
                </options>
            </control>`;
}

export function buildXml() {
  const controls = [];
  P.defaultChannels.forEach((channel, index) => {
    const deck = index + 1;
    const deckName = `Deck ${String.fromCharCode(65 + index)} (MIDI ch ${channel + 1})`;
    for (const spec of CONTROLS) {
      if (spec.note) {
        const n = P.note[spec.note];
        if (n === undefined) throw new Error(`protocol has no note "${spec.note}"`);
        controls.push(control(deckName, deck, spec, 0x90 | channel, n, "Note On"));
        controls.push(control(deckName, deck, spec, 0x80 | channel, n, "Note Off"));
      } else {
        for (const name of spec.cc) {
          const n = P.cc[name];
          if (n === undefined) throw new Error(`protocol has no cc "${name}"`);
          controls.push(control(deckName, deck, spec, 0xB0 | channel, n, `CC ${n}`));
        }
      }
    }
  });

  const files = SCRIPT_FILES.map((f) =>
    `            <file filename="${f.filename}"${f.functionprefix ? ` functionprefix="${f.functionprefix}"` : ""}/>`
  ).join("\n");

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by drivers/test/mixxx/gen-xml.mjs from drivers/common/epdj3000-protocol.js. Do not edit by hand. -->
<MixxxMIDIPreset schemaVersion="1" mixxxVersion="2.4">
    <info>
        <name>EP-DJ3000</name>
        <author>EP-DJ3000 project</author>
        <description>EP-DJ3000 scratch deck. One mapping for both decks: MIDI channel 1 is [Channel1], channel 2 is [Channel2]. Requires epdj3000-protocol.js and EP-DJ3000-scripts.js in the same folder.</description>
    </info>
    <controller id="EP-DJ3000">
        <scriptfiles>
${files}
        </scriptfiles>
        <controls>${controls.join("")}
        </controls>
    </controller>
</MixxxMIDIPreset>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const xml = buildXml();
  if (process.argv.includes("--check")) {
    if (readFileSync(XML_PATH, "utf8") !== xml) {
      console.error(`${XML_PATH} is out of date; run: node drivers/test/mixxx/gen-xml.mjs`);
      process.exit(1);
    }
    console.log("EP-DJ3000.midi.xml is up to date");
  } else {
    writeFileSync(XML_PATH, xml);
    console.log(`wrote ${XML_PATH}`);
  }
}
