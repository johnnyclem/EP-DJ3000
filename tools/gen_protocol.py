    w("// " + BANNER)
    w("// Wire contract for the EP-DJ3000. See docs/PROTOCOL.md.")
    w("#pragma once")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("namespace epdj {")
    w("namespace proto {")
    w("")
    w("constexpr uint8_t kProtocolVersion = %d;" % d["protocolVersion"])
    w("")
    m = d["midi"]
    w("// ---- MIDI ----")
    w("constexpr uint16_t kJogTicksPerRev = %d;" % m["jogTicksPerRev"])
    w("constexpr uint8_t kRelativeCenter = %d;" % m["relativeCenter"])
    w("constexpr uint8_t kDefaultChannelDeckA = %d;" % m["defaultChannels"][0])
    w("constexpr uint8_t kDefaultChannelDeckB = %d;" % m["defaultChannels"][1])
    rt = m["realtime"]
    w("constexpr uint8_t kStatusClock = %s;" % rt["clock"])
    w("constexpr uint8_t kStatusStart = %s;" % rt["start"])
    w("constexpr uint8_t kStatusContinue = %s;" % rt["continue"])
    w("constexpr uint8_t kStatusStop = %s;" % rt["stop"])
    w("constexpr uint8_t kStatusSongPosition = %s;" % rt["songPosition"])
    w("constexpr uint8_t kStatusMtcQuarterFrame = %s;" % rt["mtcQuarterFrame"])
    w("constexpr uint8_t kClockPpqn = %d;" % rt["ppqn"])
    w("constexpr uint16_t kBpmMinX10 = %d;" % rt["bpmMinX10"])
    w("constexpr uint16_t kBpmMaxX10 = %d;" % rt["bpmMaxX10"])
    w("")
    dev = d["device"]
    w("// ---- USB identity (dev placeholder VID/PID, see protocol/epdj3000.json) ----")
    w("constexpr uint16_t kUsbVendorId = %s;" % dev["usbVendorId"])
    w("constexpr uint16_t kUsbProductId = %s;" % dev["usbProductId"])
    w('constexpr const char* kProductName = "%s";' % dev["name"])
    w("constexpr const char* kDeckNames[%d] = {%s};" % (len(dev["deckNames"]), ", ".join('"%s"' % n for n in dev["deckNames"])))
    w("constexpr const char* kCableNames[%d] = {%s};" % (len(dev["cables"]), ", ".join('"%s"' % c["name"] for c in dev["cables"])))
    w("")
    ccs = [s for s in control_symbols(m) if s[0] == "cc"]
    notes = [s for s in control_symbols(m) if s[0] == "note"]
    w("namespace cc {")
    for _, ident, num in ccs:
        w("constexpr uint8_t k%s = %d;" % (ident, num))
    w("}  // namespace cc")
    w("namespace note {")
    for _, ident, num in notes:
        w("constexpr uint8_t k%s = %d;" % (ident, num))
    w("}  // namespace note")
    w("")
    w("namespace cable {")
    for c in d["device"]["cables"]:
        w("constexpr uint8_t k%s = %d;" % (camel(c["name"].replace(" ", "_")), c["cable"]))
    w("}  // namespace cable")
    w("")
    w("// ---- enums ----")
    for name, vals in d["enums"].items():
        w("enum class %s : uint8_t {" % name)
        for vn, vv in vals:
            w("  %s = %d," % (camel(vn), vv))
        w("};")
    w("")
    w("// ---- bit fields ----")
    for name, vals in d["bitfields"].items():
        wd = bitfield_width(d, name)
        t = "uint%d_t" % wd
        w("namespace %s {" % lcamel(name))
        for vn, bit in vals:
            w("constexpr %s k%s = static_cast<%s>(1u << %d);" % (t, camel(vn), t, bit))
        w("}  // namespace %s" % lcamel(name))
    w("")
    w("// ---- SysEx ----")
    w("namespace sysex {")
    w("constexpr uint8_t kManufacturerId = %s;" % d["sysex"]["header"][0])
    w("constexpr uint8_t kModelId0 = %s;" % d["sysex"]["header"][1])
    w("constexpr uint8_t kModelId1 = %s;" % d["sysex"]["header"][2])
    w("constexpr uint8_t kVersion = %d;" % d["sysex"]["version"])
    w("constexpr uint8_t kDeckAny = %d;" % d["sysex"]["deckAny"])
    w("constexpr uint8_t kReplyFlag = %s;" % hexb(d["sysex"]["replyFlag"]))
    w("constexpr uint8_t kAck = %s;" % hexb(d["sysex"]["ack"]))
    w("constexpr uint8_t kNak = %s;" % hexb(d["sysex"]["nak"]))
    w("enum class Cmd : uint8_t {")
    for c in d["sysex"]["commands"]:
        w("  %s = %s," % (camel(c["name"]), hexb(c["id"])))
    w("};")
    w("enum class Reply : uint8_t {")
    for c in d["sysex"]["replies"]:
        w("  %s = %s," % (camel(c["name"]), hexb(c["id"])))
    w("};")
    w("enum class Err : uint8_t {")
    for c in d["sysex"]["errors"]:
        w("  %s = %d," % (camel(c["name"]), c["id"]))
    w("};")
    w("}  // namespace sysex")
    w("")
    w("// ---- config ----")
    w("enum class ConfigKey : uint8_t {")
    for k in d["config"]["keys"]:
        w("  %s = %d," % (camel(k["name"]), k["id"]))
    w("};")
    w("struct ConfigDesc {")
    w("  ConfigKey key;")
    w("  const char* name;")
    w("  int32_t minValue;")
    w("  int32_t maxValue;")
    w("  int32_t defaultValue;")
    w("};")
    keys = d["config"]["keys"]
    w("constexpr size_t kConfigCount = %d;" % len(keys))
    w("constexpr ConfigDesc kConfigTable[kConfigCount] = {")
    for k in keys:
        w('  {ConfigKey::%s, "%s", %d, %d, %d},' % (camel(k["name"]), k["name"], k["min"], k["max"], k["default"]))
    w("};")
    w("")
    w("// ---- structs (little-endian, packed) ----")
    for sname, fields in d["structs"].items():
        if sname.startswith("_"):
            continue
        size = struct_size(fields)
        w("struct %s {" % sname)
        for f in fields:
            cpp = INT_TYPES[f[1]][2]
            if len(f) > 2:
                w("  %s %s[%d] = {};" % (cpp, f[0], f[2]))
            else:
                w("  %s %s = 0;" % (cpp, f[0]))
        w("  static constexpr size_t kBytes = %d;" % size)
        w("};")
        w("inline void serialize(const %s& v, uint8_t* out) {" % sname)
        w("  size_t i = 0;")
        for f in fields:
            nbytes, _, cpp, _s = INT_TYPES[f[1]]
            cnt = f[2] if len(f) > 2 else 1
            if cnt > 1:
                w("  for (size_t n = 0; n < %d; ++n) {" % cnt)
                ind = "    "
                src = "v.%s[n]" % f[0]
            else:
                ind = "  "
                src = "v.%s" % f[0]
            for b in range(nbytes):
                w("%sout[i++] = static_cast<uint8_t>((static_cast<uint32_t>(%s) >> %d) & 0xFFu);" % (ind, src, 8 * b))
            if cnt > 1:
                w("  }")
        w("}")
        w("inline bool deserialize(const uint8_t* in, size_t len, %s* v) {" % sname)
        w("  if (len < %s::kBytes) return false;" % sname)
        w("  size_t i = 0;")
        for f in fields:
            nbytes, signed, cpp, _s = INT_TYPES[f[1]]
            cnt = f[2] if len(f) > 2 else 1
            if cnt > 1:
                w("  for (size_t n = 0; n < %d; ++n) {" % cnt)
                ind = "    "
                dst = "v->%s[n]" % f[0]
            else:
                ind = "  "
                dst = "v->%s" % f[0]
            if cnt == 1:
                w("  {")
                ind = "    "
            w("%suint32_t x_ = 0;" % ind)
            for b in range(nbytes):
                w("%sx_ |= static_cast<uint32_t>(in[i++]) << %d;" % (ind, 8 * b))
            w("%s%s = static_cast<%s>(x_);" % (ind, dst, cpp))
            if cnt > 1 or cnt == 1:
                w("  }")
        w("  return true;")
        w("}")
        w("")
    w("}  // namespace proto")
    w("}  // namespace epdj")
    return "\n".join(o) + "\n"


