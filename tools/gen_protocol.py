    "extension", "false", "for", "func", "guard", "if", "import", "in", "init", "is", "let", "nil",
    "operator", "private", "protocol", "public", "repeat", "return", "self", "static", "struct",
    "subscript", "super", "switch", "throw", "throws", "true", "try", "var", "where", "while", "any",
    "internal", "open", "fileprivate", "rethrows", "deinit", "associatedtype", "typealias", "Type",
