INT_TYPES = {
    # name: (bytes, signed, cpp, swift)
    "u8": (1, False, "uint8_t", "UInt8"),
    "u16": (2, False, "uint16_t", "UInt16"),
    "u32": (4, False, "uint32_t", "UInt32"),
    "i8": (1, True, "int8_t", "Int8"),
    "i16": (2, True, "int16_t", "Int16"),
    "i32": (4, True, "int32_t", "Int32"),
}


# ---------------------------------------------------------------- naming
def words(name):
    """UPPER_SNAKE, lowerCamel or CamelCase -> list of lowercase words."""
    if "_" in name or name.isupper():
        return [w.lower() for w in name.split("_") if w]
    parts = re.findall(r"[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])", name)
    return [p.lower() for p in parts]


def camel(name):  # UpperCamel
    return "".join(w.capitalize() for w in words(name))


def lcamel(name):  # lowerCamel
    c = camel(name)
    return c[0].lower() + c[1:] if c else c


def hexb(v):
    return "0x%02X" % v


def load():
    with open(SRC) as f:
        return json.load(f)


def control_symbols(m):
    """Yield (kind, ident, number) for every CC/note constant."""
    for c in m["controls"]:
        base = camel(c["id"])
        if c["type"] == "note":
            yield ("note", base, c["number"])
        elif c["type"] == "cc14":
            yield ("cc", base + "Msb", c["number"])
            yield ("cc", base + "Lsb", c["lsb"])
        else:  # cc, ccRel
            yield ("cc", base, c["number"])


def bitfield_width(d, name):
    return d.get("bitfieldWidths", {}).get(name, 8)


def struct_size(fields):
    total = 0
    for f in fields:
        n = f[2] if len(f) > 2 else 1
        total += INT_TYPES[f[1]][0] * n
    return total


