def outputs():
    d = load()
    outs = {
        OUT_CPP: gen_cpp(d),
        OUT_SWIFT: gen_swift(d),
        OUT_JS: gen_js(d),
        OUT_JS_MIXXX: gen_js(d),
    }
    if os.path.exists(DOC_MD):
        with open(DOC_MD) as f:
            outs[DOC_MD] = apply_markers(f.read(), md_sections(d))
    return outs


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, content in outputs().items():
        cur = open(path).read() if os.path.exists(path) else None
        if cur != content:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as f:
                    f.write(content)
                print("wrote", os.path.relpath(path, ROOT))
    if check:
        if stale:
            print("STALE generated files (run tools/gen_protocol.py):")
            for s in stale:
                print("  ", os.path.relpath(s, ROOT))
            sys.exit(1)
        print("protocol artifacts up to date")
    elif not stale:
        print("nothing to do; artifacts up to date")


if __name__ == "__main__":
    main()
